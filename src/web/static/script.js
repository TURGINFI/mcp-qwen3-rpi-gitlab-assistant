// Small front-end script to talk with backend /chat endpoint

const chatLog = document.getElementById("chat-log");
const form = document.getElementById("chat-form");
const input = document.getElementById("user-input");
const sendBtn = document.getElementById("send-btn");
const statusText = document.getElementById("status-text");

// Store conversation history
let chatHistory = [];
// Limit history to prevent overwhelming the small 0.6B model
const MAX_HISTORY_LENGTH = 10; 

// Helper: create one chat bubble
function appendMessage(role, text) {
  const wrapper = document.createElement("div");
  wrapper.className = "message " + role;

  const meta = document.createElement("div");
  meta.className = "meta";
  meta.textContent = role === "user" ? "You" : "Assistant";

  const bubble = document.createElement("div");
  bubble.className = "bubble";
  bubble.textContent = text;

  const avatar = document.createElement("div");
  avatar.className = "avatar " + role;
  avatar.textContent = role === "user" ? "U" : "AI";

  const content = document.createElement("div");
  content.appendChild(meta);
  content.appendChild(bubble);

  if (role === "user") {
    // User bubble on the right side
    wrapper.appendChild(content);
    wrapper.appendChild(avatar);
  } else {
    // Assistant bubble on the left side
    wrapper.appendChild(avatar);
    wrapper.appendChild(content);
  }

  chatLog.appendChild(wrapper);
  chatLog.scrollTop = chatLog.scrollHeight;
}

// Helper: show "thinking..." message, return element id
function appendThinking() {
  const id = "assistant-thinking";
  const existing = document.getElementById(id);
  if (existing) return id;

  const wrapper = document.createElement("div");
  wrapper.className = "message assistant";
  wrapper.id = id;

  const avatar = document.createElement("div");
  avatar.className = "avatar assistant";
  avatar.textContent = "AI";

  const bubble = document.createElement("div");
  bubble.className = "bubble";
  bubble.textContent = "Assistant is thinking...";

  const content = document.createElement("div");
  const meta = document.createElement("div");
  meta.className = "meta";
  meta.textContent = "Assistant";

  content.appendChild(meta);
  content.appendChild(bubble);

  wrapper.appendChild(avatar);
  wrapper.appendChild(content);

  chatLog.appendChild(wrapper);
  chatLog.scrollTop = chatLog.scrollHeight;
  return id;
}

function removeThinking(id) {
  const el = document.getElementById(id);
  if (el) el.remove();
}

// Handle form submit
form.addEventListener("submit", async (event) => {
  event.preventDefault();
  const text = input.value.trim();
  if (!text) return;

  appendMessage("user", text);
  input.value = "";

  sendBtn.disabled = true;
  const thinkingId = appendThinking();

  try {
    const resp = await fetch("/chat", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      // Send the current message AND the conversation history
      body: JSON.stringify({ 
        message: text,
        history: chatHistory
      })
    });

    if (!resp.ok) {
      throw new Error("HTTP " + resp.status);
    }

    const data = await resp.json();

    // Try to find reply field, if not exist, print raw json
    const reply =
      data.reply ||
      data.response ||
      data.answer ||
      data.content ||
      JSON.stringify(data);

    removeThinking(thinkingId);
    appendMessage("assistant", reply);

    // Update history array with the successful exchange
    chatHistory.push({ role: "user", content: text });
    chatHistory.push({ role: "assistant", content: reply });

    // Enforce history limit
    if (chatHistory.length > MAX_HISTORY_LENGTH * 2) {
      chatHistory = chatHistory.slice(-(MAX_HISTORY_LENGTH * 2));
    }

  } catch (err) {
    removeThinking(thinkingId);
    appendMessage(
      "assistant",
      "[Error] Failed to talk with backend: " + err.message
    );
    statusText.textContent = "Backend error – please check server logs.";
  } finally {
    sendBtn.disabled = false;
    input.focus();
  }
});

// Enter / Shift+Enter behavior
input.addEventListener("keydown", (e) => {
  if (e.key === "Enter" && !e.shiftKey) {
    e.preventDefault();
    form.requestSubmit();
  }
});

